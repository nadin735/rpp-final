// BUGFIX (carried over from the scheduling tool, where this exact issue
// broke the real production build): `dict` is declared `as const` so every
// string field gets its own exact literal type. That makes dict.de,
// dict.en, and dict.ar three different, mutually incompatible types, since
// their text differs. A `Dict` type derived as `typeof dict.en` would then
// only accept the English literal values specifically, and passing `t={t}`
// with German or Arabic loaded, an everyday case, would fail to
// type-check. `Widen` strips every literal string down to the general
// `string` type, recursively, so all three language dictionaries
// structurally satisfy `Dict`.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T

export type Dict = Widen<typeof dict.en>

export const isRtl: Record<Lang, boolean> = { de: false, en: false, ar: true }
